/** Offline build: compact, hash-checked playback snapshot -> isolated ESM entries. */
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.includes('--check')
const manifest = JSON.parse(
  await readFile(join(root, 'data/manifest.sha256.json'), 'utf8'),
)
async function input(path) {
  const bytes = await readFile(join(root, 'data', path))
  assert.equal(
    createHash('sha256').update(bytes).digest('hex'),
    manifest.files[path],
    `Snapshot hash mismatch: ${path}`,
  )
  return bytes
}
const snapshot = JSON.parse(await input('snapshot.json'))
assert.equal(snapshot.schemaVersion, '2.0.0')
assert.equal(snapshot.sourceIds.length, 13)
assert.equal(new Set(snapshot.sourceIds).size, 13)
assert.equal(snapshot.surahLengths.length, 114)
assert.equal(
  snapshot.surahLengths.reduce((a, b) => a + b),
  6236,
)
const generated = new Map()
const put = (name, text) =>
  generated.set(
    name,
    '// Generated by scripts/generate-runtime.mjs; do not edit.\n' + text,
  )
put(
  'generated/dataset.ts',
  `export const snapshotInfo = ${JSON.stringify(snapshot.snapshotInfo)} as const\n`,
)
put(
  'generated/addressing.ts',
  `export const surahLengths: readonly number[] = ${JSON.stringify(snapshot.surahLengths)}\n`,
)
const targets = [-23, -20, -18, -16]
const symbols = {}
for (const sid of snapshot.sourceIds) {
  assert(/^[a-z-]+$/.test(sid))
  const { metadata, policies } = JSON.parse(await input(`sources/${sid}.json`))
  assert.equal(metadata.id, sid)
  const symbol = (symbols[sid] = sid.replace(/-([a-z])/g, (_, c) =>
    c.toUpperCase(),
  ))
  put(
    `generated/metadata/${sid}.ts`,
    `import type { AudioSource } from '../../types'\nconst metadata: AudioSource & { readonly id: ${JSON.stringify(sid)} } = ${JSON.stringify(metadata)}\nexport default metadata\n`,
  )
  for (const target of targets) {
    const policy = policies[target]
    assert(policy && (policy.base === null || Number.isInteger(policy.base)))
    const indices = new Set()
    for (const [index, gain, limited] of policy.overrides) {
      assert(
        Number.isInteger(index) &&
          index >= 0 &&
          index < 6236 &&
          !indices.has(index),
      )
      assert(
        Number.isInteger(gain) &&
          gain >= -1800 &&
          gain <= 800 &&
          typeof limited === 'boolean',
      )
      indices.add(index)
    }
    for (const [index, reason] of policy.unavailable) {
      assert(
        Number.isInteger(index) &&
          index >= 0 &&
          index < 6236 &&
          !indices.has(index),
      )
      assert(
        [
          'invalid-audio',
          'unmeasurable',
          'unprocessed',
          'missing-audio',
          'download-error',
          'peak-limit-unreachable',
        ].includes(reason),
      )
      indices.add(index)
    }
    put(
      `generated/policies/target${target}/${sid}.ts`,
      `import type { AudioSourcePolicyData } from '../../../types'\nconst policy: AudioSourcePolicyData = ${JSON.stringify({ targetLufs: target, ...policy })}\nexport default policy\n`,
    )
    const prefix = target === -20 ? '..' : '../..'
    const path =
      target === -20 ? `sources/${sid}.ts` : `targets/${target}/${sid}.ts`
    put(
      path,
      `import metadata from '${prefix}/generated/metadata/${sid}'\nimport policy from '${prefix}/generated/policies/target${target}/${sid}'\nimport { createAudioSource } from '${prefix}/playback'\nconst ${symbol} = /* @__PURE__ */ createAudioSource(metadata, policy)\nexport { ${symbol} }\nexport default ${symbol}\n`,
    )
  }
  const hashes = await input(`hashes/${sid}.bin`)
  assert.equal(hashes.length, 6236 * 32)
  put(
    `generated/hashes/${sid}.ts`,
    `const hashes: string = '${hashes.toString('hex')}'\nexport default hashes\n`,
  )
  put(
    `hashes/${sid}.ts`,
    `import hashes from '../generated/hashes/${sid}'\nimport metadata from '../generated/metadata/${sid}'\nimport { createAudioContentManifest } from '../verify'\nconst manifest = /* @__PURE__ */ createAudioContentManifest(metadata.id, metadata.contentRevision, hashes)\nexport default manifest\n`,
  )
}
put(
  'generated/source-exports.ts',
  snapshot.sourceIds
    .map((id) => `export { default as ${symbols[id]} } from '../sources/${id}'`)
    .join('\n') + '\n',
)
put(
  'catalog.ts',
  "import type { AudioSource } from './types'\n" +
    snapshot.sourceIds
      .map((id, i) => `import source${i} from './generated/metadata/${id}'`)
      .join('\n') +
    '\nexport const audioSources: readonly AudioSource[] = /* @__PURE__ */ Object.freeze([' +
    snapshot.sourceIds
      .map((_, i) => `/* @__PURE__ */ Object.freeze(source${i})`)
      .join(',') +
    '])\n',
)
put(
  'generated/loaders.ts',
  'export const sourceLoaders = {\n' +
    targets
      .map(
        (target) =>
          `${JSON.stringify(String(target))}: {\n` +
          snapshot.sourceIds
            .map(
              (id) =>
                `${JSON.stringify(id)}: () => import('${target === -20 ? '../sources' : '../targets/' + target}/${id}'),`,
            )
            .join('\n') +
          '\n},',
      )
      .join('\n') +
    '\n}\nexport const hashLoaders = {\n' +
    snapshot.sourceIds
      .map((id) => `${JSON.stringify(id)}: () => import('../hashes/${id}'),`)
      .join('\n') +
    '\n}\n',
)
for (const [path, content] of generated) {
  const destination = join(root, 'src', path)
  if (check)
    assert.equal(
      await readFile(destination, 'utf8'),
      content,
      `Stale generated module: ${path}`,
    )
  else {
    await mkdir(dirname(destination), { recursive: true })
    await writeFile(destination, content)
  }
}
console.log(
  `${check ? 'Verified' : 'Generated'} ${generated.size} isolated modules from the compact playback snapshot.`,
)
